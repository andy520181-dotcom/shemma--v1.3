#!/bin/bash
echo "=== 检查结果页关键样式是否在CSS中生成 ==="
echo ""
echo "1. 检查 border-gray-50:"
grep -q "border-gray-50\|F9FAFB" dist/assets/*.css && echo "✅ 找到" || echo "❌ 未找到"
echo ""
echo "2. 检查 shadow-[0_20px_40px:"
grep -q "shadow.*20px.*40px\|0 20px 40px" dist/assets/*.css && echo "✅ 找到" || echo "❌ 未找到"
echo ""
echo "3. 检查 bg-white:"
grep -q "bg-white" dist/assets/*.css && echo "✅ 找到" || echo "❌ 未找到"
echo ""
echo "4. 检查 text-gray-:"
grep -q "text-gray-" dist/assets/*.css && echo "✅ 找到" || echo "❌ 未找到"
